/**
 * Хто є адміністратором (Етап 7, базова модерація) — свідомо НЕ окрема
 * колонка в базі даних, а список email-адрес у налаштуваннях сервера
 * (`ADMIN_EMAILS`, через кому). Причина: призначити чи зняти
 * адміністратора тоді не вимагає ні міграції бази, ні окремої форми
 * "запросити адміна" в інтерфейсі — досить назвати мені email, і я одним
 * рядком додам його в налаштування (той самий підхід, що вже є для
 * GOOGLE_CLIENT_ID чи LIQPAY-ключів). Підтримує будь-яку кількість
 * адміністраторів одразу — рішення Артема від 02.09.2026 "одразу для
 * двох" виконується простим переліком через кому, без додаткового коду.
 *
 * Цей файл навмисно НЕ імпортує Prisma чи `@/auth` (повну, Node.js-версію
 * автентифікації) — лише рядкові операції, тому його можна безпечно
 * використовувати і в middleware.ts (Edge-рантайм, де Prisma заборонено),
 * і в звичайних сторінках/діях. Функція, що читає сесію
 * (`resolveAdminAccess`), навмисно винесена в окремий файл
 * (src/lib/admin/access.ts) — так само, як auth.config.ts відділено від
 * auth.ts.
 */
function getAdminEmails(): Set<string> {
  return new Set(
    (process.env.ADMIN_EMAILS ?? "")
      .split(",")
      .map((email) => email.trim().toLowerCase())
      .filter(Boolean),
  );
}

/** Email людини не змінюється після реєстрації (src/lib/validation/profile.ts
 * свідомо не дає його редагувати) — тому порівняння регістронезалежне і без
 * додаткового запиту в базу є безпечним і тут, і в resolveAdminAccess. */
export function isAdminEmail(email: string | null | undefined): boolean {
  if (!email) return false;
  return getAdminEmails().has(email.trim().toLowerCase());
}
